# mypackage/calculator.py

def add(a, b):
    """
    2つの数を加算して返します。

    Args:
        a (int): 1つ目の数
        b (int): 2つ目の数

    Returns:
        int: 加算結果
    """
    return a + b


def subtract(a, b):
    """
    2つの数を減算して返します。

    Args:
        a (int): 1つ目の数
        b (int): 2つ目の数

    Returns:
        int: 減算結果
    """
    return a - b
